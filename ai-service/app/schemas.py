from typing import Literal

from pydantic import BaseModel, Field, field_validator


class ExtractionRequest(BaseModel):
    # Correlation only: this service must never query Spring's database.
    consultation_id: int = Field(gt=0, alias="consultationId")

    # Reject oversized transcripts instead of silently changing their content.
    transcript: str = Field(min_length=1, max_length=12_000)

    # Versioned by the server-side caller, not by an end user.
    prompt_version: str = Field(
        default="symptom-extraction-v1",
        min_length=1,
        max_length=50,
        alias="promptVersion",
    )

    @field_validator("transcript")
    @classmethod
    def transcript_must_contain_visible_text(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("transcript must contain visible text")
        return value.strip()


class SymptomItem(BaseModel):
    # Only a constrained extraction label, never a diagnosis.
    name: str = Field(min_length=1, max_length=100)
    assertion: Literal["PRESENT", "NEGATED", "UNCERTAIN"]
    confidence: float = Field(ge=0.0, le=1.0)
    evidence: str = Field(min_length=1, max_length=500)


class GeneratedExtraction(BaseModel):
    # This is the only object generated by the model itself.
    items: list[SymptomItem]


class ExtractionResponse(GeneratedExtraction):
    # The service, not the model, supplies provenance metadata below.
    provider: Literal["openai"]
    model_name: str = Field(min_length=1, max_length=100, alias="modelName")
    prompt_version: str = Field(min_length=1, max_length=50, alias="promptVersion")
